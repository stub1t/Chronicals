const language = writable<Language>(DEFAULT_LANGUAGE);

function applyLanguage(lang: Language) {
	if (!browser) return;
	document.documentElement.lang = lang;
	localStorage.setItem(STORAGE_KEY, lang);
}

function init() {
	if (!browser) return;
	const stored = localStorage.getItem(STORAGE_KEY);
	const lang: Language = stored === 'en' || stored === 'de' ? stored : DEFAULT_LANGUAGE;
	language.set(lang);
	applyLanguage(lang);
}

function set(lang: Language) {
	language.set(lang);
	applyLanguage(lang);
}

export function t(key: keyof typeof translations.de, vars?: Record<string, string | number>): string {
	const lang = get(language);
	const template: string = translations[lang][key] ?? translations.de[key];
	if (!vars) return template;
	return Object.entries(vars).reduce(
		(text: string, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
		template
	);
}

export function dateLocale(lang = get(language)): string {
	return lang === 'en' ? 'en-US' : 'de-AT';
}

export function localizeBuiltInText(text: string | null | undefined): string {
	if (!text) return text ?? '';
	const lang = get(language);
	const table: Record<string, string> = builtInText[lang];
	return table[text] ?? text;
}

export const localeStore = {
	subscribe: language.subscribe,
	get current() {
		return get(language);
	},
	init,
	set
};

export { language };
